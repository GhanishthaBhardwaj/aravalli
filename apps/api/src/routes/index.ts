// Every endpoint, with the schema its request must satisfy. Handlers live in controllers/.
import { INCIDENT_STATUSES, RISK_CATEGORIES, RISK_STATUSES, ROLES, SEVERITIES } from '@aravalli/shared';
import type { RequestHandler } from 'express';
import { z } from 'zod';
import { registerAuthRoutes, type Limiters } from './auth';
import { makeDirectoryController } from '../controllers/directory';
import { makeIncidentsController } from '../controllers/incidents';
import { makeReportsController } from '../controllers/reports';
import { makeRisksController } from '../controllers/risks';
import { csvList, pagingQuery, queryBool } from '../core/http';
import { Registry } from '../core/registry';
import { EMPLOYEE_SORTS } from '../repositories/directory';
import { INCIDENT_SORTS } from '../repositories/incidents';
import { RISK_SORTS } from '../repositories/risks';
import type { Deps } from '../services/deps';

const order = z.enum(['asc', 'desc']).default('asc').describe('Sort direction.');
const id = z.number().int().positive();
const text = z.string().max(5000);
const q = z.string().trim().max(100).optional().describe('Search text.');

export function buildRegistry(d: Deps, authenticate: RequestHandler, limiters: Limiters): Registry {
  const r = new Registry(authenticate);
  const dir = makeDirectoryController(d);
  const risks = makeRisksController(d);
  const incidents = makeIncidentsController(d);
  const reports = makeReportsController(d);

  // ----------------------------------------------------------------- organisations (read only)
  r.add({ method: 'get', path: '/organisations/current', access: 'session', tag: 'Organisations', summary: 'The organisation of this request',
    handler: ({ req, res }) => dir.currentOrganisation(req, res) });
  r.add({ method: 'get', path: '/organisations/:id', access: 'session', tag: 'Organisations', summary: 'Read your own organisation',
    handler: ({ req, res }) => dir.organisationById(req, res) });

  // ------------------------------------------------------------------------------- departments
  r.add({ method: 'get', path: '/departments', access: 'session', tag: 'Departments', summary: 'List departments with open risk, open incident and headcount figures',
    handler: ({ req, res }) => dir.listDepartments(req, res) });
  r.add({ method: 'get', path: '/departments/:id', access: 'session', tag: 'Departments', summary: 'One department',
    handler: ({ req, res }) => dir.department(req, res) });

  // --------------------------------------------------------------------------------- employees
  r.add({
    method: 'get', path: '/employees', access: 'directory.read', tag: 'Employees', summary: 'List employees',
    query: z.object({
      q,
      department_id: z.coerce.number().int().positive().optional(),
      role: csvList(z.enum(ROLES)).default([]).describe('Comma-separated roles.'),
      active: queryBool.optional(),
      sort: z.enum(EMPLOYEE_SORTS as [string, ...string[]]).default('name'),
      order,
      ...pagingQuery,
    }),
    handler: ({ req, res, query }) => dir.listEmployees(req, res, query),
  });
  r.add({ method: 'get', path: '/employees/:id', access: 'directory.read', tag: 'Employees', summary: 'One employee', handler: ({ req, res }) => dir.employee(req, res) });

  // -------------------------------------------------------------------------------------- risks
  r.add({
    method: 'get', path: '/risks', access: 'risk.read', tag: 'Risks', summary: 'List risks with their current assessment',
    description: 'Filtering, sorting and limit/offset paging. Unrated risks always sort last.',
    query: z.object({
      q,
      statuses: csvList(z.enum(RISK_STATUSES)).optional().describe('Comma-separated statuses.'),
      categories: csvList(z.enum(RISK_CATEGORIES)).optional().describe('Comma-separated categories.'),
      bands: csvList(z.enum([...SEVERITIES, 'Unrated'])).optional().describe('Comma-separated severity bands (or Unrated).'),
      department_id: z.coerce.number().int().positive().optional(),
      owner_id: z.coerce.number().int().positive().optional(),
      likelihood: z.coerce.number().int().min(1).max(5).optional().describe('Current likelihood (heat map row).'),
      impact: z.coerce.number().int().min(1).max(5).optional().describe('Current impact (heat map column).'),
      open: queryBool.optional().describe('true: only risks that are not Closed.'),
      sort: z.enum(RISK_SORTS as [string, ...string[]]).default('code'),
      order,
      ...pagingQuery,
    }),
    handler: ({ req, res, query }) => risks.list(req, res, query),
  });
  r.add({ method: 'post', path: '/risks', access: 'risk.write', tag: 'Risks', status: 201, summary: 'Register a risk',
    description: 'The code (RSK-0001...) is generated by the database. Include likelihood and impact to record a first assessment. The reporter is the signed-in user.',
    body: z.object({
      title: z.string().max(300), description: text,
      category: z.string().max(40), department_id: id.nullable(), owner_employee_id: id.nullable(),
      identified_date: z.string().max(10),
      likelihood: z.number().int().nullable().default(null), impact: z.number().int().nullable().default(null),
      mitigation_notes: text.default(''),
    }),
    handler: ({ req, res, body }) => risks.create(req, res, body) });
  r.add({ method: 'get', path: '/risks/by-code/:code', access: 'risk.read', tag: 'Risks', summary: 'One risk by its code (RSK-0001), with assessment history',
    handler: ({ req, res }) => risks.getByCode(req, res) });
  r.add({ method: 'get', path: '/risks/:id', access: 'risk.read', tag: 'Risks', summary: 'One risk with its assessment history', handler: ({ req, res }) => risks.get(req, res) });
  r.add({ method: 'get', path: '/risks/:id/assessments', access: 'risk.read', tag: 'Risks', summary: 'Assessment history, oldest first', handler: ({ req, res }) => risks.assessments(req, res) });
  r.add({ method: 'post', path: '/risks/:id/assessments', access: 'risk.write', tag: 'Risks', status: 201, summary: 'Add an assessment',
    description: 'The score is likelihood x impact, computed by the database. Assessments are never edited, only added.',
    body: z.object({
      likelihood: z.number().int().nullable(), impact: z.number().int().nullable(),
      assessment_date: z.string().max(10), mitigation_notes: text.default(''),
    }),
    handler: ({ req, res, body }) => risks.assess(req, res, body) });
  r.add({ method: 'post', path: '/risks/:id/status', access: 'risk.write', tag: 'Risks', summary: 'Change a risk status',
    description: 'Follows the risk lifecycle in packages/shared. Closing needs a note.',
    body: z.object({ status: z.enum(RISK_STATUSES), note: text.default('') }),
    handler: ({ req, res, body }) => risks.status(req, res, body) });

  // ----------------------------------------------------------------------------------- incidents
  r.add({
    method: 'get', path: '/incidents', access: 'incident.read', tag: 'Incidents', summary: 'List incidents',
    description: 'Filtering, sorting and limit/offset paging. Newest reported first by default.',
    query: z.object({
      q,
      statuses: csvList(z.enum(INCIDENT_STATUSES)).optional().describe('Comma-separated statuses.'),
      severities: csvList(z.enum(SEVERITIES)).optional().describe('Comma-separated severities.'),
      department_id: z.coerce.number().int().positive().optional(),
      assignee_id: z.coerce.number().int().positive().optional(),
      risk_id: z.coerce.number().int().positive().optional(),
      open: queryBool.optional().describe('true: Open, Investigating, Contained. false: Resolved, Closed.'),
      unassigned: queryBool.optional().describe('true: no assignee.'),
      needs_attention: queryBool.optional().describe('true: not Closed and unassigned or unlinked.'),
      imported: queryBool.optional().describe('true: only records imported from a public dataset.'),
      sort: z.enum(INCIDENT_SORTS as [string, ...string[]]).default('reported_at'),
      order: z.enum(['asc', 'desc']).default('desc').describe('Sort direction.'),
      ...pagingQuery,
    }),
    handler: ({ req, res, query }) => incidents.list(req, res, query),
  });
  r.add({ method: 'post', path: '/incidents', access: 'incident.report', tag: 'Incidents', status: 201, summary: 'Report an incident',
    description: 'Always starts as Open. The code (INC-0001...) is generated by the database. The reporter is the signed-in user.',
    body: z.object({
      title: z.string().max(300), description: text, severity: z.string().max(20),
      department_id: id.nullable(), occurred_at: z.string().max(25),
      assigned_to: id.nullable().default(null), risk_id: id.nullable().default(null),
    }),
    handler: ({ req, res, body }) => incidents.report(req, res, body) });
  r.add({ method: 'get', path: '/incidents/by-code/:code', access: 'incident.read', tag: 'Incidents', summary: 'One incident by its code (INC-0001), with its timeline',
    handler: ({ req, res }) => incidents.getByCode(req, res) });
  r.add({ method: 'get', path: '/incidents/:id', access: 'incident.read', tag: 'Incidents', summary: 'One incident with its timeline', handler: ({ req, res }) => incidents.get(req, res) });
  r.add({ method: 'get', path: '/incidents/:id/updates', access: 'incident.read', tag: 'Incidents', summary: 'Timeline, newest first', handler: ({ req, res }) => incidents.updates(req, res) });
  r.add({ method: 'post', path: '/incidents/:id/updates', access: 'incident.update', tag: 'Incidents', status: 201, summary: 'Add a timeline entry, optionally changing the status',
    description: 'Status moves follow the incident lifecycle. Resolving needs a note and stamps resolved_at. Closed is final.',
    body: z.object({ update_text: text, status_to: z.enum(INCIDENT_STATUSES).nullable().default(null) }),
    handler: ({ req, res, body }) => incidents.addUpdate(req, res, body) });
  r.add({ method: 'patch', path: '/incidents/:id/assignment', access: 'incident.assign', tag: 'Incidents', summary: 'Assign (or unassign) an incident',
    body: z.object({ employee_id: id.nullable() }), handler: ({ req, res, body }) => incidents.assign(req, res, body) });
  r.add({ method: 'patch', path: '/incidents/:id/risk-link', access: 'incident.link', tag: 'Incidents', summary: 'Link (or unlink) an incident to a risk',
    body: z.object({ risk_id: id.nullable() }), handler: ({ req, res, body }) => incidents.linkRisk(req, res, body) });

  // ------------------------------------------------------------------------------------ reports
  r.add({ method: 'get', path: '/reports/overview', access: 'report.read', tag: 'Reports', summary: 'Dashboard figures: KPIs, incidents by status, top risks, recent activity',
    handler: ({ req, res }) => reports.overview(req, res) });
  r.add({ method: 'get', path: '/reports/heatmap', access: 'report.read', tag: 'Reports', summary: '5x5 likelihood/impact grid of open risks',
    query: z.object({ mode: z.enum(['current', 'first']).default('current').describe('current: latest assessment. first: first assessment.') }),
    handler: ({ req, res, query }) => reports.heatmap(req, res, query) });
  r.add({ method: 'get', path: '/reports/risk-profile', access: 'report.read', tag: 'Reports', summary: 'Open risks by department and severity band',
    handler: ({ req, res }) => reports.riskProfile(req, res) });
  r.add({ method: 'get', path: '/reports/resolution', access: 'report.read', tag: 'Reports', summary: 'Hours to resolve (mean and median) by severity or department',
    query: z.object({ group_by: z.enum(['severity', 'department']).default('severity') }),
    handler: ({ req, res, query }) => reports.resolution(req, res, query) });

  registerAuthRoutes(r, d, limiters);
  return r;
}
