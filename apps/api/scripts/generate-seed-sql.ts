// Generates database/seeds/demo-organisation.sql from the shared sample dataset, so the database and the
// web demo hold exactly the same data.   Run: npm run db:seed-sql
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { seed } from '@aravalli/shared';

type Cell = string | number | boolean | null | undefined;
type Row = Record<string, Cell>;

const q = (v: Cell) => {
  if (v === null || v === undefined) return 'NULL';
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? '1' : '0';
  return `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`;
};
const ts = (s: string | null) => (s === null ? null : s.replace('T', ' ').slice(0, 19));

function insert<T extends object>(table: string, cols: string[], rows: T[], map: (r: T) => Row = (r) => r as unknown as Row) {
  if (!rows.length) return '';
  const lines = rows.map((r) => {
    const m = map(r);
    return `  (${cols.map((c) => q(m[c])).join(', ')})`;
  });
  return `INSERT INTO ${table} (${cols.join(', ')}) VALUES\n${lines.join(',\n')};\n\n`;
}

let out = `-- =============================================================================
-- Sample organisation: ${seed.organisation.name} (fictional).
-- GENERATED by apps/api/scripts/generate-seed-sql.mjs from packages/shared/src/demo/seed.ts. Do not edit by hand.
-- Load after the migrations: npm run db:seed
-- risk_assessment.risk_score is a generated column and is not inserted.
-- =============================================================================

SET NAMES utf8mb4;

`;

out += insert('organisation', ['organisation_id', 'name', 'slug', 'is_demo', 'created_at'], [seed.organisation], (r) => ({ ...r, created_at: ts(r.created_at) }));
out += insert('department', ['department_id', 'organisation_id', 'code', 'name', 'created_at'], seed.departments, (r) => ({ ...r, created_at: ts(r.created_at) }));
out += insert('employee',
  ['employee_id', 'organisation_id', 'employee_code', 'department_id', 'first_name', 'last_name', 'email', 'job_title', 'role', 'is_active', 'created_at'],
  seed.employees, (r) => ({ ...r, created_at: ts(r.created_at) }));
out += insert('risk',
  ['risk_id', 'organisation_id', 'risk_code', 'title', 'description', 'category', 'department_id', 'owner_employee_id', 'status', 'identified_date', 'created_at', 'updated_at'],
  seed.risks, (r) => ({ ...r, created_at: ts(r.created_at), updated_at: ts(r.updated_at) }));
out += insert('risk_assessment',
  ['assessment_id', 'organisation_id', 'risk_id', 'assessed_by', 'assessment_date', 'likelihood', 'impact', 'mitigation_notes', 'created_at'],
  seed.risk_assessments, (r) => ({ ...r, created_at: ts(r.created_at) }));
out += insert('incident',
  ['incident_id', 'organisation_id', 'incident_code', 'title', 'description', 'severity', 'status', 'department_id', 'reported_by', 'assigned_to', 'risk_id', 'occurred_at', 'reported_at', 'resolved_at'],
  seed.incidents, (r) => ({ ...r, occurred_at: ts(r.occurred_at), reported_at: ts(r.reported_at), resolved_at: ts(r.resolved_at) }));
out += insert('incident_update',
  ['update_id', 'organisation_id', 'incident_id', 'updated_by', 'update_text', 'status_from', 'status_to', 'created_at'],
  seed.incident_updates, (r) => ({ ...r, created_at: ts(r.created_at) }));

const target = fileURLToPath(new URL('../database/seeds/demo-organisation.sql', import.meta.url));
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out, 'utf8');
console.log(
  `Wrote ${target}: 1 organisation, ${seed.departments.length} departments, ${seed.employees.length} employees, ${seed.risks.length} risks, ` +
    `${seed.risk_assessments.length} assessments, ${seed.incidents.length} incidents, ${seed.incident_updates.length} updates`,
);
